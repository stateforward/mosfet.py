"""Memory for stateforward.mosfet bots.

``Memory`` is the bot's one durable memory, a state machine reached by message only. It runs
relational statement transactions (behavior inventory and identity build SQLAlchemy Core clauses
against ``memory_table`` and friends, compile them with ``compile_statement(s)``, and send them
with ``transact``), and it keeps every cognition turn as an episode node of a graph, linked to the
persons it involves (each participant ref is exactly one person's; the bot itself is ``SELF``,
and ``PersonEvent`` declares, names, links, unlinks, forgets and lists persons), with a canonical
vector per node in its embedder's space (``Index`` /
``ExactIndex`` search it). ``Associative`` surfaces what memory associates with a turn, scored and
fit to a token budget, and brings a memory to mind in full when the bot deliberately recalls it
(the model-callable ``RecallEvent``, answered by a ``RecollectedEvent`` observation).
``Consolidation`` works through memory while the bot rests: it backfills vectors, then offers a
model one unit at a time to link, merge, forget, or leave as it is. ``StmMemory`` is the short-term
register of admitted stimuli. Facts the bot holds about itself share one row shape about
``SELF_SUBJECT``, built with ``self_fact_select_input`` and ``self_fact_insert_input``.
"""

